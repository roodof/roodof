import {chromium} from 'playwright';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('../../reports/session-reconnect-v1/preview/',import.meta.url));
const startup=(await readFile(path.join(root,'access.tmp'),'utf8')).trim();
const ids=JSON.parse(await readFile(path.join(root,'ids.json'),'utf8'));
const browser=await chromium.launch({channel:'msedge',headless:true});
const errors=[],remote=[],results=[];
try{
 for(const lang of ['en','tr']){
  const page=await browser.newPage({viewport:{width:1440,height:1050},reducedMotion:'reduce'});
  page.on('pageerror',e=>errors.push(e.message));page.on('request',req=>{if(new URL(req.url()).origin!==new URL(startup).origin)remote.push(new URL(req.url()).origin);});
  const url=new URL(startup);url.searchParams.set('lang',lang);
  await page.goto(url.href);await page.waitForFunction(()=>usageState.data?.has_snapshot&&!usageState.loading);
  if(await page.locator('#first-use').isVisible())await page.locator('.first-use-actions .primary').click();
  await page.locator('[data-route=settings]').click();
  const panel=page.locator('#session-reconnections');await panel.scrollIntoViewIfNeeded();
  const source=panel.locator('[data-reconnect-kind=sources][data-id="'+ids.source+'"]');await source.waitFor();
  await source.click();
  await panel.locator('#reconnect-search-targets').fill(ids.far);
  await panel.locator('[data-reconnect-kind=targets][data-id="'+ids.far+'"]').waitFor();
  await panel.locator('#reconnect-search-targets').fill(ids.target);
  await panel.locator('[data-reconnect-kind=targets][data-id="'+ids.target+'"]').click();
  const before=await page.evaluate(()=>api('/api/usage?days=0'));
  const savedBefore=await page.evaluate(()=>api('/api/usage/reconnections?kind=state'));
  await panel.locator('[data-reconnect-action=preview]').click();
  const confirm=panel.locator('[data-reconnect-action=transfer]');await confirm.waitFor();
  assert(await panel.locator('input[type=radio]').first().evaluate(node=>node.getBoundingClientRect().width<=20));
  assert(await panel.locator('.reconnection-choice label').first().evaluate(node=>node.querySelector('span').getBoundingClientRect().right<=node.closest('.reconnection-preview').getBoundingClientRect().right));
  assert(await confirm.isDisabled());
  await panel.locator('input[name=reconnect-verdict][value=target]').check();
  await panel.locator('input[name=reconnect-budget][value=source]').check();
  assert(await confirm.isDisabled());
  await panel.locator('.reconnect-consent').check();assert(await confirm.isEnabled());
  const previewState=await page.evaluate(()=>api('/api/usage/reconnections?kind=state'));
  assert.equal(previewState.revision,savedBefore.revision);
  await panel.screenshot({path:path.join(root,'preview-'+lang+'.png')});
  await confirm.click();
  await page.waitForFunction(()=>document.querySelector('#session-reconnections [data-reconnect-action=undo]')?.disabled===false);
  const after=await page.evaluate(()=>api('/api/usage?days=0'));
  assert(before.totals&&Object.keys(before.totals).length>0);assert.deepEqual(after.totals,before.totals);
  const moved=await page.evaluate(id=>api('/api/usage/session?id='+id),ids.target);
  assert.equal(moved.session.verdict,'wasted');
  const watches=await page.evaluate(()=>api('/api/usage/budgets'));
  assert(!watches.items.some(row=>row.id===ids.source));assert.equal(watches.items.find(row=>row.id===ids.target).limit,900);
  await panel.locator('[data-reconnect-action=undo]').click();
  await page.waitForFunction(()=>document.querySelector('#session-reconnections [data-reconnect-action=undo]')?.disabled===true);
  const restored=await page.evaluate(id=>api('/api/usage/session?id='+id),ids.source);assert.equal(restored.session.verdict,'useful');
  // A second window changes metadata after a preview. Confirmation must refuse.
  await panel.locator('[data-reconnect-action=reload]').click();await source.click();
  await panel.locator('[data-reconnect-kind=targets][data-id="'+ids.target+'"]').click();
  await panel.locator('[data-reconnect-action=preview]').click();await confirm.waitFor();
  await panel.locator('input[name=reconnect-verdict][value=target]').check();await panel.locator('input[name=reconnect-budget][value=source]').check();await panel.locator('.reconnect-consent').check();
  await page.evaluate(id=>post('/api/usage/verdict',{id,verdict:'useful'}),ids.target);
  await confirm.click();await page.waitForFunction(()=>document.querySelector('.reconnection-status').dataset.state==='error');
  assert((await panel.locator('.reconnection-status').textContent()).includes(lang==='tr'?'değişti':'changed'));
  assert.equal((await page.evaluate(id=>api('/api/usage/session?id='+id),ids.source)).session.verdict,'useful');
  await page.evaluate(id=>post('/api/usage/verdict',{id,verdict:'wasted'}),ids.target);
  await page.setViewportSize({width:390,height:1000});await panel.scrollIntoViewIfNeeded();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(root,'narrow-'+lang+'.png')});
  results.push({lang,preview_read_only:true,explicit_choices:true,transfer:true,undo:true,stale_preview_refused:true,search_beyond_400:true,no_overflow:true});
  await page.close();
 }
 assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
 await writeFile(path.join(root,'ui-check.json'),JSON.stringify({results,script_errors:errors,external_requests:remote},null,2));
 console.log('Reconnection preview, choices, transfer, undo and conflict checks passed');
}finally{await browser.close();}
